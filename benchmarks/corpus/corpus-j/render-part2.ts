import { readFile, writeFile } from 'node:fs/promises';
import { renderMarkdown, ROOT } from './parity.js';
import type { CorpusHReport } from '../corpus-h/parity.js';
async function main() {
  const report = JSON.parse(await readFile(`${ROOT}/part2-outcomes.json`, 'utf8'));
  const metrics = report.fixtures.flatMap((row: any) => row.comparisons.flatMap((comparison: any) =>
    Object.entries(comparison.metrics.signals).filter(([, metric]: any) => metric.status === 'compared').map(([signal, metric]: any) =>
      `| ${row.id} | ${comparison.analysis} ${signal} | ${metric.sampleCount} | ${metric.absoluteError.max} | ${metric.absoluteError.rms} | ${metric.relativeError.max ?? 'unavailable'} | ${metric.relativeError.rms ?? 'unavailable'} |`)));
  const combinedWall = report.actualCumulativeChildWallMs;
  const display = { ...report, policy: { ...report.policy, deterministicHashExcludes: ['environment', 'tools.node', 'ngspice.analyses', 'spiceTs.analyses'] },
    gapBuckets: report.gapBuckets.map((bucket: any) => ({ ...bucket, issue: bucket.bucket === 'directive: .title' ? 'https://github.com/mfiumara/spice-ts/issues/957' : bucket.bucket === 'execution: other failure' ? 'https://github.com/mfiumara/spice-ts/issues/956 (j-14 only; j-19 has no reference)' : bucket.issue })) };
  const markdown = renderMarkdown(display as CorpusHReport)
    .replace('# corpus-j: partial novel source survey (#940)', '# corpus-j part 2: nine original fixtures (#940)')
    .replace('Generated by `pnpm exec tsx benchmarks/corpus/corpus-j/parity.ts`', 'Generated by `pnpm exec tsx benchmarks/corpus/corpus-j/render-part2.ts`')
    .replace('- none\n', '- https://github.com/mfiumara/spice-ts/issues/956: nested DC TEMP (j-14).\n- https://github.com/mfiumara/spice-ts/issues/957: .title metadata (j-16).\n');
  await writeFile(`${ROOT}/PART2.md`, markdown + `
## Delivery and export limits

Nine new original input hashes bring the manifest to 20. Historical j-1..j-11 outcomes.json and wall.jsonl remain byte-identical to #947; their 11 both-failed outcomes are not upgraded by this delivery. Part 2 adds five ngspice raw successes, three matched rows, two spice-ts-only losses and four both-failed rows. The combined 20-row catalogue therefore has 3 matched, 2 spice-ts-only losses and 15 both-failed. Input-hash novelty is not a claim of nine novel topology families.

Control decks use unchanged corpus-f runControlReference instead of batch-only raw capture: a source/write wrapper receives original bytes, defers quit/exit and exports first plot per declared type. No circuit, analysis or tolerance is rewritten. Subsequent control plots are not compared; j-14 fails spice-ts during a later nested TEMP sweep even though ngspice's exported dc1 belongs to the first voltage/body sweep. Success here requires actual raw vectors. Batch plots cannot open a GUI and DISPLAY is removed by the control wrapper.

The matched criterion and breakpoint-aware/linear metrics are unchanged. Null/empty metrics mean unavailable, never measured zero. Fine-step adapted references are not run. Cold engine groups are serial, 19 s execution deadline/20 s boundary; the persisted cumulative budget includes historical attempts. Measured combined child wall: ${combinedWall} ms. No speed superiority claim. No simulator change: this is an expansion from 0 ngspice-successful rows in the historical 11 to 5 across the 20, not a before/after solver performance comparison. Nightly #855 owns aggregate incorporation.

## Issue deduplication

Searched open and closed GitHub issues for .title, title in:title, dot command, dc temp, temperature sweep and DC sweep source before filing:

- j-14: [#956](https://github.com/mfiumara/spice-ts/issues/956), nested DC TEMP source lookup. #318 implements .step TEMP LIST, not control DC TEMP.
- j-16: [#957](https://github.com/mfiumara/spice-ts/issues/957), .title after a comment title line. #790 covers other harmless directives, not .title.
- j-17/j-18/j-20: both engines reject original .backanno; no spice-ts-only issue.
- j-19: ngspice fails with PMOS Nsub < Ni, spice-ts rejects missing AC source in .sens; no reference, no spice-ts-only issue.

Both new issues have label bug and milestone M1 Correctness parity. No simulator fixes in this PR.

## Matched-point metrics

All compared signals below; relative metrics exclude zero reference samples under the unchanged shared rule. Full grid exclusions, missing signals and linear-interpolation metrics are in part2-outcomes.json.

| Fixture | Signal | Points | Max abs | RMS abs | Max rel | RMS rel |
|---|---|---|---|---|---|---|
${metrics.join('\n')}

## Commands

    pnpm install --frozen-lockfile
    pnpm build && pnpm lint
    spice-heavy pnpm exec tsx benchmarks/corpus/corpus-j/part2.ts
    pnpm exec tsx benchmarks/corpus/corpus-j/render-part2.ts
    pnpm exec tsx --test benchmarks/corpus/corpus-j/corpus-j.test.ts benchmarks/corpus/corpus-j/part2.test.ts
    spice-heavy pnpm test

Source ingestion is append-part2.ts against the original 11-row manifest and pinned checkouts documented in SOURCES.md; never rerun legacy select.ts/parity.ts over the appended manifest. Offline tests verify fixture/licence hashes, dedup, manifest reconstruction, all outcome rows, metric availability and cumulative wall accounting. Required exact-head CI and independent review govern publication; local logs do not replace that gate.
`);
}
main().catch(error => { console.error(error); process.exitCode = 1; });
