"""Offline, fail-closed translation of pinned ngspice47 BSIM4 model setup.

Usage: python3 generate-setup.py /absolute/path/to/ngspice47 [--check]
Only params.ts, model-defaults.ts and model-parameters.json are generated.
Raw model-card conversions in b4mpar.c are deliberately NOT applied here.
"""
import argparse
import json
from pathlib import Path
import re
import subprocess

SOURCE_SHA = 'a80f6e3e95d51534905b1f23410a951802666656'
FIRST_LINE = 78
LAST_LINE = 2304


def git(source: Path, *args: str) -> str:
    return subprocess.check_output(['git', '-C', str(source), *args], text=True).strip()


def generate(source: Path) -> dict[str, str]:
    source = source.resolve()
    if git(source, 'rev-parse', 'HEAD') != SOURCE_SHA:
        raise ValueError(f'Source checkout must be pinned to {SOURCE_SHA}')
    if git(source, 'status', '--porcelain', '--untracked-files=all'):
        raise ValueError('Source checkout must be clean (including untracked files)')
    directory = source / 'src/spicelib/devices/bsim4'
    setup = (directory / 'b4set.c').read_text()
    table = (directory / 'b4.c').read_text()
    setter = (directory / 'b4mpar.c').read_text()
    # Ignore commented-out definitions; retain original offsets for provenance.
    def uncomment(text: str) -> str:
        return re.sub(r'/\*.*?\*/|//[^\n]*', lambda m: ''.join('\n' if c == '\n' else ' ' for c in m[0]), text, flags=re.S)

    entries: dict[str, list[tuple[str, str, int]]] = {}
    pattern = r'\b(?:IOP\w*|IP\w*)\(\s*"([^"]+)"\s*,\s*(BSIM4_MOD_\w+)\s*,\s*(IF_\w+)'
    for match in re.finditer(pattern, uncomment(table)):
        name, identifier, kind = match.groups()
        assert name == name.lower(), name
        entries.setdefault(identifier, []).append((name, kind, table.count('\n', 0, match.start()) + 1))
    fields: dict[str, str] = {'type': 'type', 'v48intVersion': 'v48intversion'}
    names: list[str] = []
    integers: list[str] = []
    aliases: dict[str, str] = {}
    refs: dict[str, str] = {}
    cases = list(re.finditer(r'\bcase\s+(BSIM4_MOD_\w+)\s*:', uncomment(setter)))
    for index, case in enumerate(cases):
        identifier = case[1]
        body = uncomment(setter)[case.end():cases[index + 1].start() if index + 1 < len(cases) else len(setter)]
        assigned = re.findall(r'mod->BSIM4(\w+)\s*=(?!=)', body)
        assigned = [field for field in assigned if not field.endswith('Given')]
        assert assigned, identifier
        assert len(set(assigned)) == 1, (identifier, assigned)
        field = assigned[0]
        assert identifier in entries, f'No model-card name for {identifier}'
        definitions = entries[identifier]
        if field == 'type':
            # NMOS/PMOS are polarity flags, not aliases of a numeric card parameter.
            continue
        canonical = definitions[0][0]
        assert field not in fields, (field, identifier)
        fields[field] = canonical
        names.append(canonical)
        refs[canonical] = f'b4.c:{definitions[0][2]}, b4mpar.c:{setter.count(chr(10), 0, case.start()) + 1}'
        if definitions[0][1] == 'IF_INTEGER':
            integers.append(canonical)
        assert definitions[0][1] in ('IF_INTEGER', 'IF_REAL', 'IF_STRING'), definitions
        for alias, kind, _ in definitions[1:]:
            assert kind == definitions[0][1]
            aliases[alias] = canonical
    assert len(names) == len(set(names)), 'Duplicate canonical model-card names'
    names += ['type', 'v48intversion']
    integers += ['type', 'v48intversion']
    header = setup[:setup.index('#include')].rstrip() + '\n\n'
    provenance = f'// Modified/ported to TypeScript by spice-ts.\n// Generated by generate-setup.py; DO NOT EDIT.\n// Source: ngspice47 {SOURCE_SHA}\n'
    params = header + provenance + '// Canonical model-card names joined by BSIM4_MOD IDs, not C member names.\n'
    params += 'export const MODEL_PARAMETER_NAMES = [\n'
    for name in names:
        params += f"  '{name}', // {refs.get(name, 'internal setup field')}\n"
    params += '] as const;\n\nexport type Bsim4ModelParameter = (typeof MODEL_PARAMETER_NAMES)[number];\n'
    params += "\n/** Caller initializes numerical fields to zero and version to ''; given flags stay separate. */\n"
    params += "export type Bsim4ModelValues = {\n  [K in Bsim4ModelParameter]: K extends 'version' ? string : number;\n};\n"
    params += '\nexport const MODEL_ALIASES = {\n'
    for alias, canonical in aliases.items():
        params += f"  '{alias}': '{canonical}',\n"
    params += '} as const satisfies Readonly<Record<string, Bsim4ModelParameter>>;\n'
    params += '\nexport const MODEL_INTEGER_PARAMETERS = [\n'
    params += ''.join(f"  '{name}',\n" for name in integers)
    params += '] as const satisfies readonly Bsim4ModelParameter[];\n'

    lines = setup.splitlines(keepends=True)[FIRST_LINE - 1:LAST_LINE]
    body = ''.join(lines)
    assert lines[0].strip() == 'if (!model->BSIM4typeGiven)'
    assert lines[-1].strip() == 'model->BSIM4pku0we = 0;'
    # Preserve comments verbatim while translating only executable source tokens.
    comments: list[str] = []
    def save_comment(match: re.Match) -> str:
        comments.append(match[0])
        return f'__COMMENT_{len(comments) - 1}__' + '\n' * match[0].count('\n')
    body = re.sub(r'/\*.*?\*/', save_comment, body, flags=re.S)
    body = re.sub(r'printf\("(?:[^"\\]|\\.)*"\);', '', body)
    def member(match: re.Match) -> str:
        field = match[1]
        given = field.endswith('Given')
        if given:
            field = field[:-5]
        assert field in fields, f'Unmapped setup member: {field}'
        name = fields[field]
        return f"given.has('{name}')" if given else f'values.{name}'
    body = re.sub(r'model->BSIM4(\w+)', member, body)
    body = re.sub(r'!strcmp\((values\.version),\s*("[^"]+")\)', r'\1 === \2', body)
    body = re.sub(r'!strncmp\((values\.version),\s*("[^"]+"),\s*(\d+)\)', r'\1.startsWith(\2.slice(0, \3))', body)
    body = re.sub(r'\bcopy\(("[^"]+")\)', r'\1', body)
    body = body.replace('ckt->CKTnomTemp', 'nominalTemperatureK')
    body = re.sub(r'\bBSIM4v48V(\d+)\b', r'\1', body)
    body = re.sub(r'\bNMOS\b', '1', body)
    body = re.sub(r'\bPMOS\b', '-1', body)
    assert not re.search(r'->|\b(?:printf|strcmp|strncmp|copy|BSIM4\w+)\b', body), 'Untranslated C tokens'
    # Every nonempty translated line retains its original source line number.
    output = []
    for number, line in enumerate(body.splitlines(), FIRST_LINE):
        if not line.strip():
            output.append('')
            continue
        line = re.sub(r'^ {0,8}', '', line)
        line = re.sub(r'__COMMENT_(\d+)__', lambda m: comments[int(m[1])], line)
        output.append(f'  {line} // b4set.c:{number}')
    defaults = header + provenance + f'// Mechanically ordered b4set.c:{FIRST_LINE}-{LAST_LINE}; warning output omitted.\n'
    defaults += "import type { Bsim4ModelParameter, Bsim4ModelValues } from './params.js';\n\n"
    defaults += '/** Mutates zero-initialized values; does not alter given flags or perform raw-card unit conversions.\n * Caller guards supported versions/selectors. Preserve upstream broad 4.8 prefix behavior. */\n'
    defaults += 'export function applyModelDefaults(\n  values: Bsim4ModelValues,\n  given: ReadonlySet<Bsim4ModelParameter>,\n  nominalTemperatureK: number,\n): void {\n'
    defaults += '\n'.join(output) + '\n}\n'
    manifest = {
        'sourceSha': SOURCE_SHA,
        'sourceFile': 'src/spicelib/devices/bsim4/b4set.c',
        'sourceLines': [FIRST_LINE, LAST_LINE],
        'modelParameters': names,
        'internalFields': ['type', 'v48intversion'],
        'aliases': aliases,
    }
    return {'params.ts': params, 'model-defaults.ts': defaults,
            'model-parameters.json': json.dumps(manifest, indent=2) + '\n'}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path, help='Explicit clean pinned ngspice47 checkout')
    parser.add_argument('--check', action='store_true', help='Verify generated files without writing')
    args = parser.parse_args()
    for filename, content in generate(args.source).items():
        target = Path(__file__).resolve().parent / filename
        if args.check:
            if not target.exists() or target.read_text() != content:
                raise SystemExit(f'Generated file differs: {target}')
        else:
            target.write_text(content)
        print(f'{"Verified" if args.check else "Generated"} {filename}')


if __name__ == '__main__':
    main()
